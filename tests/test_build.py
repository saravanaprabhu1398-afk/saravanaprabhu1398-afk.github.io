import contextlib
import io
import json
import tempfile
import unittest
from datetime import datetime, timezone
from pathlib import Path
from unittest.mock import patch

from tools import build, linkedin


def post(**changes):
    item = dict(slug='example', title=r'Matching \d at C:\notes', summary=r'Keep \1 and \n literal',
                topic='Tooling', date=datetime(2026, 11, 25, tzinfo=timezone.utc),
                draft=False, linkedin='Read more\n{url}', url='https://example.com/blog/example/')
    item.update(changes)
    return item


class BuildTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.output = io.StringIO()
        self.redirect = contextlib.redirect_stdout(self.output)
        self.redirect.__enter__()
        self.addCleanup(self.redirect.__exit__, None, None, None)

    def test_home_replacement_preserves_backslashes(self):
        index = self.root / 'index.html'
        index.write_text(build.HOME_START + 'old' + build.HOME_END)
        with patch.object(build, 'INDEX', index):
            build.update_home([post()])
        self.assertIn(post()['title'], index.read_text())
        self.assertIn(post()['summary'], index.read_text())

    def test_cta_books_a_call_only_when_a_link_is_set(self):
        with patch.object(build.SD, 'BOOKING_URL', ''):
            self.assertIn('data-preview="contact"', build.render_cta())
            self.assertEqual(build.render_contact_book(), '')
        with patch.object(build.SD, 'BOOKING_URL', 'https://cal.example/me'):
            self.assertIn('href="https://cal.example/me"', build.render_cta())
            self.assertNotIn('data-preview', build.render_cta())
            self.assertIn('Book a 30-minute call', build.render_contact_book())

    def test_project_replacement_preserves_backslashes(self):
        source = '<!--PROJECTS:ALL:START-->old<!--PROJECTS:ALL:END-->'
        block = r'<p>Regex \d+, reference \1, C:\notes</p>'
        self.assertIn(block, build.sub_block(source, 'PROJECTS:ALL', block))

    def test_new_outbox_is_staged_and_url_expanded(self):
        with patch.object(build, 'OUTBOX', self.root):
            self.assertEqual(len(build.write_outbox([post()])), 1)
        self.assertEqual((self.root / 'example.txt').read_text(), 'Read more\n' + post()['url'])

    def test_pending_edits_survive_rebuild(self):
        target = self.root / 'example.txt'
        target.write_text('My manually edited copy')
        with patch.object(build, 'OUTBOX', self.root):
            self.assertEqual(build.write_outbox([post()]), [])
        self.assertEqual(target.read_text(), 'My manually edited copy')
        self.assertIn('--restage example', self.output.getvalue())

    def test_posted_copy_is_not_requeued(self):
        archive = self.root / 'posted'
        archive.mkdir()
        (archive / 'example.txt').write_text('Previously posted')
        with patch.object(build, 'OUTBOX', self.root):
            self.assertEqual(build.write_outbox([post()]), [])
        self.assertFalse((self.root / 'example.txt').exists())

    def test_explicit_restage_preserves_archive(self):
        archive = self.root / 'posted'
        archive.mkdir()
        (archive / 'example.txt').write_text('Previously posted')
        (self.root / 'example.txt').write_text('Manual copy')
        with patch.object(build, 'OUTBOX', self.root):
            self.assertEqual(len(build.write_outbox([post()], restage='example')), 1)
        self.assertIn(post()['url'], (self.root / 'example.txt').read_text())
        self.assertEqual((archive / 'example.txt').read_text(), 'Previously posted')

    def test_nested_generated_post_is_removed_and_live_kept(self):
        for name in ['old', 'live']:
            folder = self.root / name
            (folder / 'assets' / 'nested').mkdir(parents=True)
            (folder / 'index.html').write_text('<!-- Generated by tools/build.py -->')
            (folder / 'assets' / 'nested' / 'chart.svg').write_text('<svg/>')
        with patch.object(build, 'BLOG_DIR', self.root):
            build.clean_old_posts({'live'})
        self.assertFalse((self.root / 'old').exists())
        self.assertTrue((self.root / 'live' / 'assets' / 'nested' / 'chart.svg').exists())

    def test_legacy_generated_post_is_removed(self):
        folder = self.root / 'old'
        folder.mkdir()
        (folder / 'index.html').write_text('<script type="application/ld+json">{"@type": "BlogPosting"}</script>')
        with patch.object(build, 'BLOG_DIR', self.root):
            build.clean_old_posts(set())
        self.assertFalse(folder.exists())

    def test_unrecognized_directory_is_preserved(self):
        folder = self.root / 'manual'
        folder.mkdir()
        (folder / 'notes.txt').write_text('Do not delete')
        with patch.object(build, 'BLOG_DIR', self.root), self.assertRaisesRegex(ValueError, 'unrecognized'):
            build.clean_old_posts(set())
        self.assertTrue((folder / 'notes.txt').exists())

    def test_symlink_is_not_followed(self):
        outside = self.root / 'outside'
        outside.mkdir()
        blog = self.root / 'blog'
        blog.mkdir()
        (blog / 'old').symlink_to(outside, target_is_directory=True)
        with patch.object(build, 'BLOG_DIR', blog), self.assertRaisesRegex(ValueError, 'symlink'):
            build.clean_old_posts(set())
        self.assertTrue(outside.exists())

    def test_asset_version_and_dialog_sync(self):
        for rel, _ in build.PAGES:
            path = self.root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('<link href="/site.css?v=old">\n'
                            "<script>document.documentElement.classList.add('js')</script>\n"
                            '<!--SHARED:NAV-->old<!--/SHARED:NAV-->\n'
                            '<!--SHARED:FOOT-->old<!--/SHARED:FOOT-->')
        (self.root / '404.html').write_text('<link href="/site.css?v=old">')
        with patch.object(build, 'ROOT', self.root):
            build.sync_pages()
        for rel in ['index.html', 'projects/index.html', 'about/index.html', '404.html']:
            source = (self.root / rel).read_text()
            self.assertIn('/site.css?v=' + build.ASSET_V, source)
            self.assertNotIn("classList.add('js')", source)
            if rel != '404.html':
                self.assertIn('<dialog class="palette"', source)
                self.assertIn('/site.js?v=' + build.ASSET_V, source)

    def test_drafts_stay_out_of_feed_and_search(self):
        with patch.object(build, 'ROOT', self.root):
            build.write_search_index([post(draft=True)])
        self.assertNotIn(post()['url'], build.render_feed([post(draft=True)]))
        self.assertFalse(any(item['k'] == 'Post' for item in json.loads((self.root / 'search-index.json').read_text())))


class LinkedInTests(unittest.TestCase):
    def test_payload_matches_text_and_article_contract(self):
        payload, link = linkedin.build_payload('example', 'Text only', 'test-person')
        self.assertIsNone(link)
        self.assertNotIn('content', payload)
        self.assertEqual(payload['author'], 'urn:li:person:test-person')
        self.assertEqual(payload['distribution']['feedDistribution'], 'MAIN_FEED')
        payload, link = linkedin.build_payload('example', 'Read more\nhttps://example.com/', 'test-person')
        self.assertEqual(payload['content']['article']['source'], link)
        self.assertEqual(payload['content']['article']['title'], 'Example')

    def test_publish_uses_supported_version_and_does_not_requeue(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'example.txt').write_text('Copy\nhttps://example.com/')
            with patch.object(linkedin, 'OUTBOX', root), \
                    patch.object(linkedin, 'load_token', return_value={'sub': 'test-person', 'access_token': 'test-only'}), \
                    patch.object(linkedin, 'request', return_value=(201, {'x-restli-id': 'urn:li:share:test'}, {})) as request, \
                    patch('builtins.input', return_value='example'), \
                    contextlib.redirect_stdout(io.StringIO()):
                linkedin.cmd_post('example')
            self.assertEqual(request.call_args.kwargs['headers']['LinkedIn-Version'], '202611')
            self.assertEqual(request.call_args.kwargs['method'], 'POST')
            self.assertFalse((root / 'example.txt').exists())
            self.assertTrue((root / 'posted' / 'example.txt').exists())
            with patch.object(build, 'OUTBOX', root), contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(build.write_outbox([post()]), [])
            self.assertFalse((root / 'example.txt').exists())

    def test_wrong_confirmation_never_calls_network(self):
        with patch.object(linkedin, 'load_token', return_value={'sub': 'test-person'}), \
                patch.object(linkedin, 'read_draft', return_value='Copy'), \
                patch.object(linkedin, 'request') as request, \
                patch('builtins.input', return_value='no'), \
                contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            with self.assertRaises(SystemExit):
                linkedin.cmd_post('example')
            request.assert_not_called()


if __name__ == '__main__':
    unittest.main()
